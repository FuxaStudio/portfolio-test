// I18N ENGINE
// ================================

window.i18n = (function () {
  const DEFAULT_LANG = 'cs';
  const STORAGE_KEY = 'pf_lang';

  function getLang() {
    return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
  }

  function t(key) {
    const lang = getLang();
    return (window.translations[lang] && window.translations[lang][key]) || key;
  }

  function applyTranslations(lang) {
    const dict = window.translations[lang];
    if (!dict) return;

    // Text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const val = dict[el.getAttribute('data-i18n')];
      if (val !== undefined) el.textContent = val;
    });

    // Inner HTML (for titles with nested gradient spans / <br>)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const val = dict[el.getAttribute('data-i18n-html')];
      if (val !== undefined) el.innerHTML = val;
    });

    // Placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const val = dict[el.getAttribute('data-i18n-placeholder')];
      if (val !== undefined) el.placeholder = val;
    });

    // Aria-label attributes (tlacitka bez viditelneho textu)
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const val = dict[el.getAttribute('data-i18n-aria')];
      if (val !== undefined) el.setAttribute('aria-label', val);
    });

    // Update <html lang> attribute
    document.documentElement.lang = lang;

    // Update page <title> and meta description
    const page = document.documentElement.getAttribute('data-page');
    if (page) {
      const titleVal = dict['page.' + page + '.title'];
      const metaVal  = dict['page.' + page + '.meta'];
      if (titleVal) document.title = titleVal;
      const metaEl = document.querySelector('meta[name="description"]');
      if (metaEl && metaVal) metaEl.setAttribute('content', metaVal);
    }
  }

  // Jazyky jsou dva, takze prepinac ma jediny mozny cil - popisek proto neposiluje
  // "cestina/anglictina", ale rovnou akci, ktera se stane po kliknuti.
  function otherLang(lang) {
    return lang === 'cs' ? 'en' : 'cs';
  }

  function updateSwitcher(lang) {
    const cil = otherLang(lang);
    const popis = cil === 'en' ? 'Switch language to English' : 'Přepnout jazyk na češtinu';

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
      btn.setAttribute('aria-label', popis);
    });

    document.querySelectorAll('.lang-switcher').forEach(sw => {
      sw.setAttribute('aria-label', popis);
    });
  }

  function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    applyTranslations(lang);
    updateSwitcher(lang);
  }

  function init() {
    const lang = getLang();
    if (lang !== DEFAULT_LANG) applyTranslations(lang);
    updateSwitcher(lang);

    // Kliknuti kamkoli na prepinac (vcetne aktivni polozky a okraju) prepne na
    // druhy jazyk. Pri dvou jazycich je vysledek stejny, jako kdyby se clovek
    // trefil primo do neaktivniho tlacitka - jen se nemusi mirit.
    document.querySelectorAll('.lang-switcher').forEach(sw => {
      sw.addEventListener('click', () => setLang(otherLang(getLang())));
    });
  }

  // Auto-init on DOM ready
  document.addEventListener('DOMContentLoaded', init);

  return { getLang, setLang, t };
})();
